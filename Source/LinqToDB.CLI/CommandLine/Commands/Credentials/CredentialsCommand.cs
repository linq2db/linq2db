		public override async ValueTask<int> Execute(
			CliController                  controller,
			ICliEnvironment                environment,
			string[]                       rawArgs,
			Dictionary<CliOption, object?> options,
			IReadOnlyCollection<string>    unknownArgs,
			CancellationToken              cancellationToken)
		{
			options.Remove(_credentials,                            out var credentialsValue);
			options.Remove(_user,                                   out var userValue);
			options.Remove(_force,                                  out var forceValue);
			options.Remove(QueryExecutionCliOptions.CredentialsCli, out var credentialsCliValue);
			options.Remove(_config,                                 out var configValue);
			options.Remove(_profile,                                out var profileValue);
			options.Remove(_store,                                  out var storeValue);
			options.Remove(_output,                                 out var outputValue);

			if (options.Count > 0)
				throw new InvalidOperationException($"Not all options handled by {Name} command");

			var credentials    = (string?)credentialsValue;
			var user           = (string?)userValue;
			var force          = (bool?)forceValue ?? false;
			var credentialsCli = (string?)credentialsCliValue;
			var config         = (string?)configValue;
			var profile        = (string?)profileValue;
			var store          = (string?)storeValue;
			var output         = (string?)outputValue;

			if (unknownArgs.Count == 2 && string.Equals(unknownArgs.First(), "cli", StringComparison.Ordinal))
			{
				if (!string.Equals(unknownArgs.Last(), "init", StringComparison.Ordinal))
				{
					await environment.Error.WriteLineAsync($"Unknown credentials cli operation '{unknownArgs.Last()}'. Expected init.");
					return StatusCodes.INVALID_ARGUMENTS;
				}

				if (credentials != null || user != null || credentialsCli != null || profile != null)
				{
					await environment.Error.WriteLineAsync("Credentials cli init accepts only '--store', '--output', '--config', and '--force'.");
					return StatusCodes.INVALID_ARGUMENTS;
				}

				return await InitStore(environment, store, output, config, force);
			}

			if (unknownArgs.Count != 1)
			{
				await environment.Error.WriteLineAsync("Credentials operation must be one of: set, list, remove, clear, cli init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (store != null || output != null)
			{
				await environment.Error.WriteLineAsync("Options '--store' and '--output' are supported only by credentials cli init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			var operation = unknownArgs.Single();

			if (operation is not ("set" or "list" or "remove" or "clear"))
			{
				await environment.Error.WriteLineAsync($"Unknown credentials operation '{operation}'. Expected set, list, remove, clear, or cli init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (!await ValidateOperationOptions(environment, operation, credentials, user, force))
				return StatusCodes.INVALID_ARGUMENTS;

			if (profile != null && config == null)
			{
				await environment.Error.WriteLineAsync($"Option '--{_profile.Name}' requires option '--{_config.Name}'.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			var resolver    = new ConnectionSettingsResolver(environment);
			var profileName = profile ?? QueryExecutionDefaults.DefaultProfileName;

			QueryExecutionConfiguration? configuration = null;
			string?                      configFile    = null;

			if (config != null)
			{
				configFile = resolver.ResolvePath(_config, config);

				if (configFile == null || string.Equals(configFile, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
					return StatusCodes.INVALID_ARGUMENTS;

				if (!QueryExecutionConfiguration.TryLoad(environment, configFile, profileName, out configuration, out var loadError))
				{
					await environment.Error.WriteLineAsync(loadError);
					return StatusCodes.INVALID_ARGUMENTS;
				}
			}

			// The record for set and remove: --credentials, else the profile's credentials.
			string? recordName = null;

			if (operation is "set" or "remove")
			{
				recordName = await GetRecordName(environment, resolver, credentials, configuration, configFile, profileName);

				if (recordName == null)
					return StatusCodes.INVALID_ARGUMENTS;
			}

			if (!CredentialStoreSelector.TrySelect(environment, credentialsCli, configuration, configFile, out var choice, out var selectError))
			{
				await environment.Error.WriteLineAsync(selectError);
				return StatusCodes.INVALID_ARGUMENTS;
			}

			// Never on standard output: it carries the command's result (list output is piped).
			await environment.Error.WriteLineAsync($"Using {choice.Describe()}.");
			await WriteStoreNotes(environment, choice);

			var credentialStore = CredentialStoreSelector.Create(environment, choice);
			var storeText       = config != null ? $"{choice.Name} (profile '{profileName}')" : choice.Name;

			switch (operation)
			{
				case "set":
				{
					if (!environment.TryReadSecret("Password: ", out var password, out var passwordError))
					{
						await environment.Error.WriteLineAsync(passwordError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!environment.TryReadSecret("Confirm password: ", out var confirmation, out var confirmationError))
					{
						await environment.Error.WriteLineAsync(confirmationError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!string.Equals(password, confirmation, StringComparison.Ordinal))
					{
						await environment.Error.WriteLineAsync("Passwords do not match.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!credentialStore.TryStore(recordName!, user!, password!, out var storeError))
					{
						await environment.Error.WriteLineAsync(storeError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (choice.IsOsDefault && credentialStore is LocalCredentialStore { KeyCreated: true } local)
					{
						await environment.Error.WriteLineAsync(
							$"Created the local store in {local.Directory}: an encrypted file and its key, readable only by you; a copy of both opens it. "
							+ "For the desktop keyring or GPG: dotnet linq2db credentials cli init --store keyring|gpg");
					}

					await environment.Out.WriteLineAsync($"Stored {DisplayTarget(choice, recordName!)} for {user} in {storeText}.");
					return StatusCodes.SUCCESS;
				}

				case "list":
				{
					if (!credentialStore.TryList(out var records, out var diagnostics, out var listError))
					{
						await environment.Error.WriteLineAsync(listError);
						return StatusCodes.EXPECTED_ERROR;
					}

					foreach (var diagnostic in diagnostics)
						await environment.Error.WriteLineAsync(diagnostic);

					if (records.Count == 0)
					{
						await environment.Out.WriteLineAsync(diagnostics.Count == 0
							? $"No linq2db credential records in {storeText}."
							: $"No readable linq2db credential records in {storeText}.");
						return StatusCodes.SUCCESS;
					}

					var targets     = records.Select(static record => CredentialTargets.Prefix + record.Name).ToArray();
					var targetWidth = Math.Max("RECORD".Length, targets.Max(static target => target.Length));

					await environment.Out.WriteLineAsync($"{"RECORD".PadRight(targetWidth)}  USER");

					for (var i = 0; i < records.Count; i++)
						await environment.Out.WriteLineAsync($"{targets[i].PadRight(targetWidth)}  {records[i].User}");

					return StatusCodes.SUCCESS;
				}

				case "remove":
				{
					if (!credentialStore.TryRemove(recordName!, out var removed, out var removeError))
					{
						await environment.Error.WriteLineAsync(removeError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!removed)
					{
						await environment.Error.WriteLineAsync($"{DisplayTarget(choice, recordName!)} was not found in {storeText}.");
						return StatusCodes.EXPECTED_ERROR;
					}

					await environment.Out.WriteLineAsync($"Removed {DisplayTarget(choice, recordName!)} from {storeText}.");
					return StatusCodes.SUCCESS;
				}

				default:
				{
					if (!credentialStore.TryGetCount(out var count, out var countError))
					{
						await environment.Error.WriteLineAsync(countError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (count == 0)
					{
						await environment.Out.WriteLineAsync($"No linq2db credential records in {storeText}.");
						return StatusCodes.SUCCESS;
					}

					if (!force)
					{
						await environment.Error.WriteAsync($"Remove all {count.ToString(CultureInfo.InvariantCulture)} linq2db credential records from {storeText}? [y/N] ");

						var answer = environment.ReadLine();

						if (!string.Equals(answer, "y", StringComparison.OrdinalIgnoreCase)
							&& !string.Equals(answer, "yes", StringComparison.OrdinalIgnoreCase))
						{
							await environment.Out.WriteLineAsync("Credential records were not removed.");
							return StatusCodes.SUCCESS;
						}
					}

					if (!credentialStore.TryClear(out var removedCount, out var clearError))
					{
						await environment.Error.WriteLineAsync(clearError);
						return StatusCodes.EXPECTED_ERROR;
					}

					await environment.Out.WriteLineAsync($"Removed {removedCount.ToString(CultureInfo.InvariantCulture)} linq2db credential record(s) from {storeText}.");
					return StatusCodes.SUCCESS;
				}
			}
		}

		static async ValueTask<bool> ValidateOperationOptions(ICliEnvironment environment, string operation, string? credentials, string? user, bool force)
		{
			switch (operation)
			{
				case "set":
					if (string.IsNullOrWhiteSpace(user))
					{
						await environment.Error.WriteLineAsync("Option '--user' must be specified for credentials set.");
						return false;
					}

					if (force)
					{
						await environment.Error.WriteLineAsync("Option '--force' is supported only by credentials clear and credentials cli init.");
						return false;
					}

					return true;

				case "remove":
					if (user != null || force)
					{
						await environment.Error.WriteLineAsync("Credentials remove does not accept '--user' or '--force'.");
						return false;
					}

					return true;

				case "list":
					if (credentials != null || user != null || force)
					{
						await environment.Error.WriteLineAsync("Credentials list does not accept '--credentials', '--user', or '--force': it lists every linq2db record of one store.");
						return false;
					}

					return true;

				default:
					if (credentials != null || user != null)
					{
						await environment.Error.WriteLineAsync("Credentials clear does not accept '--credentials' or '--user': it removes every linq2db record of one store.");
						return false;
					}

					return true;
			}
		}

		/// <summary>
		/// Returns the record name (without <c>linq2db/</c>) for set and remove: <c>--credentials</c>, else the profile's
		/// <c>credentials</c>. Only linq2db's own records are managed here.
		/// </summary>
		static async ValueTask<string?> GetRecordName(ICliEnvironment environment, ConnectionSettingsResolver resolver, string? option, QueryExecutionConfiguration? configuration, string? configFile, string profileName)
		{
			var target = option != null
				? resolver.ResolveEnvironmentVariables(_credentials, option)
				: resolver.ResolveEnvironmentVariables(QueryExecutionCliOptions.Credentials, configuration?.Credentials);

			if (string.Equals(target, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
				return null;

			if (target == null)
			{
				await environment.Error.WriteLineAsync(configFile != null
					? $"Configuration file '{configFile}' profile '{profileName}' has no 'credentials'; add \"credentials\": \"linq2db/{profileName}\" or pass --credentials linq2db/<name>."
					: "Option '--credentials linq2db/<name>' must be specified, or '--config' with a profile that sets 'credentials'.");
				return null;
			}

			if (!CredentialTargets.IsLinq2Db(target))
			{
				await environment.Error.WriteLineAsync($"Credential record '{target}' is not a linq2db record: credentials set and remove manage only records named linq2db/<name>.");
				return null;
			}

			if (!CredentialTargets.TryNormalize(target, out _, out var error))
			{
				await environment.Error.WriteLineAsync(error);
				return null;
			}

			return target.Substring(CredentialTargets.Prefix.Length);
		}

		/// <summary>The record as the store keeps it: case-folded except in Windows Credential Manager.</summary>
		static string DisplayTarget(CredentialStoreChoice choice, string name)
		{
			var target = CredentialTargets.Prefix + name;
			return choice.Kind == CredentialStoreKind.CredentialManager ? target : target.ToLowerInvariant();
		}

		/// <summary>
		/// Lines that make the silent Linux/macOS default visible: a generated script next to the local store is used only
		/// when named, and a store inside a git working tree must not be committed.
		/// </summary>
		static async ValueTask WriteStoreNotes(ICliEnvironment environment, CredentialStoreChoice choice)
		{
			if (choice.Kind != CredentialStoreKind.Local || choice.Directory == null)
				return;

			if (choice.IsOsDefault)
			{
				foreach (var store in new[] { "keyring", "gpg" })
				{
					var script = Path.Combine(choice.Directory, CredentialStoreSelector.GetScriptFileName(store));

					if (environment.FileExists(script))
						await environment.Error.WriteLineAsync($"note: {script} is used only when named (--credentials-cli @{store} or \"credentialsCli\": \"@{store}\").");
				}
			}

			if (CredentialsDirectory.IsInsideGitWorkTree(choice.Directory))
				await environment.Error.WriteLineAsync($"Warning: the credentials directory '{choice.Directory}' is inside a git working tree; never commit {LocalCredentialStore.KeyFileName} or {LocalCredentialStore.DataFileName}.");
		}

		static async ValueTask<int> InitStore(ICliEnvironment environment, string? store, string? output, string? config, bool force)
		{
			var isWindows = OperatingSystem.IsWindows();

			if (store == null)
			{
				await environment.Error.WriteLineAsync("Option '--store' must be specified for credentials cli init: keyring (desktop keyring through secret-tool), gpg (pass), or local (built-in encrypted store).");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (store is not ("keyring" or "gpg" or "local"))
			{
				await environment.Error.WriteLineAsync($"Unknown store '{store}'. Expected keyring, gpg, or local.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (isWindows && store is ("keyring" or "gpg"))
			{
				await environment.Error.WriteLineAsync($"The {store} store is a generated sh script for Linux and macOS; on Windows use Windows Credential Manager (the default), '--store local', or a credentials CLI.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (store is "local" && output != null)
			{
				await environment.Error.WriteLineAsync("Option '--output' is not supported with '--store local': the local store has no script; its files are in the credentials directory.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (output != null && output.IndexOfAny(['"', '\'']) >= 0)
			{
				await environment.Error.WriteLineAsync("Option '--output' must not contain quotes: the path is recorded in the configuration as a command line.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (!CredentialsDirectory.TryResolve(isWindows, environment.GetEnvironmentVariable, out var directory, out var directoryError))
			{
				await environment.Error.WriteLineAsync(directoryError);
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (output == null && CredentialsDirectory.IsInsideGitWorkTree(directory))
				await environment.Error.WriteLineAsync($"Warning: the credentials directory '{directory}' is inside a git working tree; never commit its files.");

			var resolver = new ConnectionSettingsResolver(environment);

			string? configFile = null;

			if (config != null)
			{
				configFile = resolver.ResolvePath(_config, config);

				if (configFile == null || string.Equals(configFile, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
					return StatusCodes.INVALID_ARGUMENTS;
			}

			string? scriptPath = null;

			if (store is not "local")
			{
				if (output != null)
				{
					var resolved = resolver.ResolvePath(_output, output);

					if (resolved == null || string.Equals(resolved, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
						return StatusCodes.INVALID_ARGUMENTS;

					scriptPath = Path.GetFullPath(resolved);
				}
				else
				{
					scriptPath = Path.Combine(directory, CredentialStoreSelector.GetScriptFileName(store));
				}
			}

			var recorded = store is "local"
				? CredentialStoreSelector.Local
				: string.Equals(scriptPath, Path.Combine(directory, CredentialStoreSelector.GetScriptFileName(store)), StringComparison.Ordinal)
					? "@" + store
					: scriptPath!.IndexOfAny([' ', '\t']) >= 0 ? $"\"{scriptPath}\"" : scriptPath!;

			// Validate the configuration change before anything is written.
			JsonObject? root            = null;
			string?     previousContent = null;

			if (configFile != null)
			{
				if (environment.FileExists(configFile))
				{
					if (!ConfigInitCommand.TryLoadRoot(environment, configFile, out root))
						return StatusCodes.EXPECTED_ERROR;

					previousContent = environment.ReadAllText(configFile);
				}
				else
				{
					root = new JsonObject();
				}

				var defaultNode = root[QueryExecutionDefaults.DefaultProfileName];

				if (defaultNode is not (null or JsonObject))
				{
					await environment.Error.WriteLineAsync($"Configuration file '{configFile}' profile '{QueryExecutionDefaults.DefaultProfileName}' must be object.");
					return StatusCodes.EXPECTED_ERROR;
				}

				var existing = (defaultNode as JsonObject)?["credentialsCli"];

				if (existing != null && !force && !(existing is JsonValue value && value.TryGetValue<string>(out var existingValue) && string.Equals(existingValue, recorded, StringComparison.Ordinal)))
				{
					await environment.Error.WriteLineAsync($"Configuration file '{configFile}' profile '{QueryExecutionDefaults.DefaultProfileName}' already sets 'credentialsCli' to {existing.ToJsonString()}. Use '--force' to replace it.");
					return StatusCodes.EXPECTED_ERROR;
				}

				if (root[QueryExecutionDefaults.DefaultProfileName] is not JsonObject defaultProfile)
					root[QueryExecutionDefaults.DefaultProfileName] = defaultProfile = new JsonObject();

				defaultProfile["credentialsCli"] = recorded;
			}

			string? temporaryScript = null;
			var     replaced        = false;

			if (store is "local")
			{
				// The key is created first, so problems show up now; it is never rolled back (a key without data is harmless).
				var local = new LocalCredentialStore(directory, environment.GetEnvironmentVariable("USERPROFILE"));

				if (!local.TryInitialize(out var initError))
				{
					await environment.Error.WriteLineAsync(initError);
					return StatusCodes.EXPECTED_ERROR;
				}

				await environment.Out.WriteLineAsync(local.KeyCreated
					? $"Created the local store in {directory}: an encrypted file and its key, readable only by you; a copy of both opens it."
					: $"The local store in {directory} already exists; its key was kept.");
			}
			else
			{
				if (Directory.Exists(scriptPath))
				{
					await environment.Error.WriteLineAsync($"Cannot write '{scriptPath}': it is a directory.");
					return StatusCodes.EXPECTED_ERROR;
				}

				replaced = File.Exists(scriptPath);

				if (replaced && !force)
				{
					await environment.Error.WriteLineAsync($"'{scriptPath}' already exists. Use '--force' to replace it.");
					return StatusCodes.EXPECTED_ERROR;
				}

				var error = output == null
					? (CredentialsDirectory.TryEnsure(directory, out var ensureError) ? null : ensureError)
					: null;

				error ??= TryWriteTemporaryScript(scriptPath!, CredentialsCliTemplates.Get(store)!, out temporaryScript);

				if (error != null)
				{
					await environment.Error.WriteLineAsync(error);
					return StatusCodes.EXPECTED_ERROR;
				}
			}

			// The configuration and the script change together: the new script is in place only when the configuration
			// that names it was written, and a failed final rename restores the previous configuration.
			try
			{
				if (configFile != null)
				{
					var directoryName = Path.GetDirectoryName(configFile);
					if (!string.IsNullOrEmpty(directoryName))
						environment.CreateDirectory(directoryName);

					if (!await ConfigInitCommand.TryWriteConfiguration(environment, configFile, root!.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + Environment.NewLine))
						return StatusCodes.EXPECTED_ERROR;
				}

				if (temporaryScript != null)
				{
					try
					{
						environment.MoveFile(temporaryScript, scriptPath!, true);
					}
					catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
					{
						var restored = configFile == null || await RestoreConfiguration(environment, configFile, previousContent);

						await environment.Error.WriteLineAsync(configFile == null
							? $"Cannot write '{scriptPath}': {ex.Message}"
							: restored
								? $"Cannot write '{scriptPath}': {ex.Message}. The configuration file '{configFile}' was restored; '{scriptPath}' is unchanged."
								: $"Cannot write '{scriptPath}': {ex.Message}. Restoring the configuration file '{configFile}' failed too; check that it does not name '{recorded}'.");
						return StatusCodes.EXPECTED_ERROR;
					}
				}
			}
			finally
			{
				if (temporaryScript != null && File.Exists(temporaryScript))
					File.Delete(temporaryScript);
			}

			if (store is not "local")
			{
				await environment.Out.WriteLineAsync(store is "gpg"
					? $"{(replaced ? "Replaced" : "Created")} '{scriptPath}': a credentials CLI that keeps passwords with pass, one GPG-encrypted file per password in ~/.password-store. Review it; it is yours to edit."
					: $"{(replaced ? "Replaced" : "Created")} '{scriptPath}': a credentials CLI that keeps passwords in your desktop keyring (GNOME Keyring or KWallet) through secret-tool. Review it; it is yours to edit.");
			}

			if (configFile != null)
			{
				await environment.Out.WriteLineAsync($"Recorded \"credentialsCli\": {JsonSerializer.Serialize(recorded)} in profile '{QueryExecutionDefaults.DefaultProfileName}' of '{configFile}'.");
				await environment.Out.WriteLineAsync($"Check it: {CommandName} list --config {ShellQuote(configFile, isWindows)}");
			}
			else
			{
				if (store is "local" && !isWindows)
					await environment.Out.WriteLineAsync("local is already the default store on this OS; nothing needs to name it.");
				else
					await environment.Out.WriteLineAsync($"It is used only when named: --credentials-cli {ShellQuote(recorded, isWindows)}, or \"credentialsCli\": {JsonSerializer.Serialize(recorded)} in a configuration profile.");

				await environment.Out.WriteLineAsync(store is "local" && !isWindows
					? $"Check it: {CommandName} list"
					: $"Check it: {CommandName} list --credentials-cli {ShellQuote(recorded, isWindows)}");
			}

			if (store is not "local")
			{
				var tool = CredentialsCliTemplates.GetTool(store);

				if (!CredentialsCliCommandResolver.TryResolve(tool, null, false, environment.GetEnvironmentVariable("PATH"), null, File.Exists, out _, out _))
					await environment.Error.WriteLineAsync($"Warning: '{tool}' was not found on PATH. Install it ({CredentialsCliTemplates.GetToolPackage(store)}) before using the store.");
			}

			return StatusCodes.SUCCESS;
		}

		static async ValueTask<bool> RestoreConfiguration(ICliEnvironment environment, string configFile, string? previousContent)
		{
			if (previousContent != null)
				return await ConfigInitCommand.TryWriteConfiguration(environment, configFile, previousContent);

			try
			{
				environment.DeleteFile(configFile);
				return true;
			}
			catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
			{
				return false;
			}
		}

		/// <summary>
		/// Writes the script owner-only (0700) to a new temporary file next to <paramref name="path"/>, creating a missing
		/// directory owner-only. Returns an error message, or <see langword="null"/>.
		/// </summary>
		static string? TryWriteTemporaryScript(string path, string contents, out string? temporaryFile)
		{
			temporaryFile = null;

			try
			{
				var directory = Path.GetDirectoryName(path)!;

				if (!Directory.Exists(directory))
				{
					if (OperatingSystem.IsWindows())
						Directory.CreateDirectory(directory);
					else
						Directory.CreateDirectory(directory, CredentialsDirectory.DirectoryMode);
				}

				var temporary = Path.Combine(directory, $".{Path.GetFileName(path)}.{Guid.NewGuid():N}.tmp");
				var options   = new FileStreamOptions
				{
					Mode   = FileMode.CreateNew,
					Access = FileAccess.Write,
					Share  = FileShare.None,
				};

				if (!OperatingSystem.IsWindows())
					options.UnixCreateMode = CredentialsDirectory.ScriptMode;

				using var stream = new FileStream(temporary, options);

				temporaryFile = temporary;

				var bytes = new UTF8Encoding(false).GetBytes(contents);
				stream.Write(bytes, 0, bytes.Length);
				stream.Flush(flushToDisk: true);

				return null;
			}
			catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
			{
				return $"Cannot write '{path}': {ex.Message}{CredentialsDirectory.AccessHint(ex)}";
			}
		}

		/// <summary>Quotes a value for the user's shell when it needs quoting (POSIX sh on Linux/macOS, PowerShell/cmd on Windows).</summary>
		internal static string ShellQuote(string value, bool isWindows)
		{
			if (value.Length > 0 && value.All(static c => char.IsAsciiLetterOrDigit(c) || c is '@' or '/' or '.' or '-' or '_' or ':' or '\\' or '+' or ','))
				return value;

			return isWindows
				? "\"" + value.Replace("\"", "\\\"", StringComparison.Ordinal) + "\""
				: "'" + value.Replace("'", "'\\''", StringComparison.Ordinal) + "'";
		}
