	/// <summary>
	/// Manages credential profiles in Windows Credential Manager (the Windows default) or in a configured external credential
	/// helper (every OS), and generates starter helper scripts.
	/// </summary>
	sealed class CredentialsCommand : CliCommand
	{
		static readonly OptionCategory _credentialOptions   = new(1, "Credential",   "Credential profile options",           "credential");
		static readonly OptionCategory _storeOptions        = new(2, "Store",        "Credential store selection",           "store");
		static readonly OptionCategory _confirmationOptions = new(3, "Confirmation", "Destructive operation confirmation", "confirmation");
		static readonly OptionCategory _helperInitOptions   = new(4, "Helper init",  "Starter helper script generation",     "helperInit");

		static readonly CliOption _config = new StringCliOption(
			"config",
			null,
			false,
			false,
			"configuration file whose 'default' profile sets credentialHelper; for helper init, the file to record the generated helper in; supports %NAME% and ${NAME} environment variable expansion");

		static readonly CliOption _backend = new StringEnumCliOption(
			"backend",
			null,
			false,
			false,
			"secret store used by the starter script generated by credentials helper init",
			null,
			null,
			null,
			false,
			new StringEnumOption(false, false, "secret-tool", "Secret Service (GNOME Keyring, KWallet) through secret-tool from libsecret-tools"),
			new StringEnumOption(false, false, "pass",        "pass, the standard unix password manager (gpg-encrypted files)"));

		static readonly CliOption _output = new StringCliOption(
			"output",
			'o',
			false,
			false,
			"path of the script generated by credentials helper init; defaults to $XDG_CONFIG_HOME/linq2db/helpers/<backend>.sh (~/.config/linq2db/helpers/<backend>.sh); supports %NAME% and ${NAME} environment variable expansion");

		static readonly CliOption _profile = new StringCliOption(
			"profile",
			null,
			false,
			false,
			"credential profile name without the automatic linq2db/ target prefix");

		static readonly CliOption _user = new StringCliOption(
			"user",
			null,
			false,
			false,
			"database user name stored in the credential profile");

		static readonly CliOption _force = new BooleanCliOption(
			"force",
			null,
			false,
			"credentials clear: remove all linq2db credential profiles without an interactive confirmation; credentials helper init: replace an existing script and credentialHelper value",
			null,
			null,
			null,
			false,
			false);

		public static CliCommand Instance { get; } = new CredentialsCommand();

		CredentialsCommand()
			: base(
				"credentials",
				true,
				false,
				"<set|list|remove|clear|helper init> [options]",
				"manage linq2db credential profiles. Without a credential helper, profiles live in Windows Credential Manager on Windows; other operating systems need an external credential helper "
				+ "(any program speaking the linq2db credential helper protocol), selected with --credential-helper or by credentialHelper in the 'default' profile of --config. "
				+ "'helper init' writes a starter helper script for secret-tool or pass (Linux, macOS)",
				[
					new("dotnet linq2db credentials set --profile project-a/production-read --user ProjectReader", "securely prompts for and stores a password"),
					new("dotnet linq2db credentials list", "lists linq2db credential profile names and users"),
					new("dotnet linq2db credentials remove --profile project-a/production-read", "removes one credential profile"),
					new("dotnet linq2db credentials clear", "removes all linq2db credential profiles after confirmation"),
					new("dotnet linq2db credentials helper init --backend secret-tool --config .agents/linq2db-query.json", "writes a starter secret-tool helper script and records it in the configuration's default profile"),
					new("dotnet linq2db credentials set --config .agents/linq2db-query.json --profile project-a/production-read --user ProjectReader", "stores a password through the credential helper configured in the default profile"),
					new("dotnet linq2db credentials list --credential-helper /usr/local/bin/my-credential-helper", "lists profiles stored by an explicit credential helper"),
				],
				true)
		{
			AddOption(_credentialOptions,   _profile);
			AddOption(_credentialOptions,   _user);
			AddOption(_storeOptions,        QueryExecutionCliOptions.CredentialHelper);
			AddOption(_storeOptions,        _config);
			AddOption(_confirmationOptions, _force);
			AddOption(_helperInitOptions,   _backend);
			AddOption(_helperInitOptions,   _output);
		}

		public override async ValueTask<int> Execute(
			CliController                  controller,
			ICliEnvironment                environment,
			string[]                       rawArgs,
			Dictionary<CliOption, object?> options,
			IReadOnlyCollection<string>    unknownArgs,
			CancellationToken              cancellationToken)
		{
			options.Remove(_profile,                                  out var profileValue);
			options.Remove(_user,                                     out var userValue);
			options.Remove(_force,                                    out var forceValue);
			options.Remove(QueryExecutionCliOptions.CredentialHelper, out var helperValue);
			options.Remove(_config,                                   out var configValue);
			options.Remove(_backend,                                  out var backendValue);
			options.Remove(_output,                                   out var outputValue);

			if (options.Count > 0)
				throw new InvalidOperationException($"Not all options handled by {Name} command");

			var profile = (string?)profileValue;
			var user    = (string?)userValue;
			var force   = (bool?)forceValue ?? false;
			var helper  = (string?)helperValue;
			var config  = (string?)configValue;
			var backend = (string?)backendValue;
			var output  = (string?)outputValue;

			if (unknownArgs.Count == 2 && string.Equals(unknownArgs.First(), "helper", StringComparison.Ordinal))
			{
				if (!string.Equals(unknownArgs.Last(), "init", StringComparison.Ordinal))
				{
					await environment.Error.WriteLineAsync($"Unknown credentials helper operation '{unknownArgs.Last()}'. Expected init.");
					return StatusCodes.INVALID_ARGUMENTS;
				}

				if (profile != null || user != null || helper != null)
				{
					await environment.Error.WriteLineAsync("Credentials helper init accepts only '--backend', '--output', '--config', and '--force'.");
					return StatusCodes.INVALID_ARGUMENTS;
				}

				return await InitHelper(environment, backend, output, config, force);
			}

			if (unknownArgs.Count != 1)
			{
				await environment.Error.WriteLineAsync("Credentials operation must be one of: set, list, remove, clear, helper init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (backend != null || output != null)
			{
				await environment.Error.WriteLineAsync("Options '--backend' and '--output' are supported only by credentials helper init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			var operation = unknownArgs.Single();

			if (operation is not ("set" or "list" or "remove" or "clear"))
			{
				await environment.Error.WriteLineAsync($"Unknown credentials operation '{operation}'. Expected set, list, remove, clear, or helper init.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			var store = await GetStore(environment, helper, config);

			if (store == null)
				return StatusCodes.INVALID_ARGUMENTS;

			if (store is HelperCredentialStore helperStore)
				await environment.Error.WriteLineAsync($"Using credential helper '{helperStore.Describe()}'.");

			switch (operation)
			{
				case "set":
					if (!ValidateProfile(environment, profile) || string.IsNullOrWhiteSpace(user))
					{
						if (string.IsNullOrWhiteSpace(user))
							await environment.Error.WriteLineAsync("Option '--user' must be specified for credentials set.");

						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (force)
					{
						await environment.Error.WriteLineAsync("Option '--force' is supported only by credentials clear and credentials helper init.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!environment.TryReadSecret("Password: ", out var password, out var passwordError))
					{
						await environment.Error.WriteLineAsync(passwordError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!environment.TryReadSecret("Confirm password: ", out var confirmation, out var confirmationError))
					{
						await environment.Error.WriteLineAsync(confirmationError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!string.Equals(password, confirmation, StringComparison.Ordinal))
					{
						await environment.Error.WriteLineAsync("Passwords do not match.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!store.TryStore(profile!, user, password!, out var storeError))
					{
						await environment.Error.WriteLineAsync(storeError);
						return StatusCodes.EXPECTED_ERROR;
					}

					await environment.Out.WriteLineAsync(store is HelperCredentialStore
						? $"Stored credential profile '{profile}' as target '{HelperCredentialStore.TargetPrefix}{profile!.ToLowerInvariant()}'."
						: $"Stored credential profile '{profile}' as target 'linq2db/{profile}'.");
					return StatusCodes.SUCCESS;

				case "list":
					if (profile != null || user != null || force)
					{
						await environment.Error.WriteLineAsync("Credentials list does not accept '--profile', '--user', or '--force'.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!store.TryList(out var profiles, out var diagnostics, out var listError))
					{
						await environment.Error.WriteLineAsync(listError);
						return StatusCodes.EXPECTED_ERROR;
					}

					foreach (var diagnostic in diagnostics)
						await environment.Error.WriteLineAsync(diagnostic);

					if (profiles.Count == 0)
					{
						await environment.Out.WriteLineAsync(diagnostics.Count == 0
							? "No linq2db credential profiles found."
							: "No readable linq2db credential profiles found.");
						return StatusCodes.SUCCESS;
					}

					var profileWidth = Math.Max("PROFILE".Length, profiles.Max(static credential => credential.Name.Length));

					await environment.Out.WriteLineAsync($"{"PROFILE".PadRight(profileWidth)}  USER");

					foreach (var credential in profiles)
						await environment.Out.WriteLineAsync($"{credential.Name.PadRight(profileWidth)}  {credential.User}");

					return StatusCodes.SUCCESS;

				case "remove":
					if (!ValidateProfile(environment, profile))
						return StatusCodes.INVALID_ARGUMENTS;

					if (user != null || force)
					{
						await environment.Error.WriteLineAsync("Credentials remove accepts only '--profile'.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!store.TryRemove(profile!, out var removed, out var removeError))
					{
						await environment.Error.WriteLineAsync(removeError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (!removed)
					{
						await environment.Error.WriteLineAsync($"Credential profile '{profile}' was not found.");
						return StatusCodes.EXPECTED_ERROR;
					}

					await environment.Out.WriteLineAsync($"Removed credential profile '{profile}'.");
					return StatusCodes.SUCCESS;

				case "clear":
					if (profile != null || user != null)
					{
						await environment.Error.WriteLineAsync("Credentials clear does not accept '--profile' or '--user'.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					if (!store.TryGetCount(out var profileCount, out var countError))
					{
						await environment.Error.WriteLineAsync(countError);
						return StatusCodes.EXPECTED_ERROR;
					}

					if (profileCount == 0)
					{
						await environment.Out.WriteLineAsync("No linq2db credential profiles found.");
						return StatusCodes.SUCCESS;
					}

					if (!force)
					{
						await environment.Error.WriteAsync($"Remove all {profileCount.ToString(CultureInfo.InvariantCulture)} linq2db credential profiles? [y/N] ");

						var answer = environment.ReadLine();

						if (!string.Equals(answer, "y", StringComparison.OrdinalIgnoreCase)
							&& !string.Equals(answer, "yes", StringComparison.OrdinalIgnoreCase))
						{
							await environment.Out.WriteLineAsync("Credential profiles were not removed.");
							return StatusCodes.SUCCESS;
						}
					}

					if (!store.TryClear(out var removedCount, out var clearError))
					{
						await environment.Error.WriteLineAsync(clearError);
						return StatusCodes.EXPECTED_ERROR;
					}

					await environment.Out.WriteLineAsync($"Removed {removedCount.ToString(CultureInfo.InvariantCulture)} linq2db credential profile(s).");
					return StatusCodes.SUCCESS;

				default:
					throw new InvalidOperationException($"Unexpected credentials operation '{operation}'.");
			}
		}

		/// <summary>
		/// Returns the store the command works on: the helper named by <c>--credential-helper</c>, or by <c>credentialHelper</c>
		/// in the <c>default</c> profile of <c>--config</c>, otherwise the platform default store.
		/// </summary>
		static async ValueTask<ICredentialStore?> GetStore(ICliEnvironment environment, string? helper, string? config)
		{
			var resolver = new ConnectionSettingsResolver(environment);

			if (helper != null && config != null)
			{
				await environment.Error.WriteLineAsync($"Options '--{QueryExecutionCliOptions.CredentialHelper.Name}' and '--{_config.Name}' cannot be combined.");
				return null;
			}

			if (config == null)
				return resolver.GetCredentialStore(helper, null, null);

			var configFile = resolver.ResolvePath(_config, config);

			if (configFile == null || string.Equals(configFile, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
				return null;

			if (!QueryExecutionConfiguration.TryLoad(environment, configFile, QueryExecutionDefaults.DefaultProfileName, out var configuration, out var error))
			{
				await environment.Error.WriteLineAsync(error);
				return null;
			}

			if (configuration!.CredentialHelper == null)
			{
				await environment.Error.WriteLineAsync($"Configuration file '{configFile}' profile '{QueryExecutionDefaults.DefaultProfileName}' doesn't set 'credentialHelper'. The credentials command uses the credential helper of the '{QueryExecutionDefaults.DefaultProfileName}' profile.");
				return null;
			}

			return resolver.GetCredentialStore(null, configuration, Path.GetDirectoryName(configFile));
		}

		static async ValueTask<int> InitHelper(ICliEnvironment environment, string? backend, string? output, string? config, bool force)
		{
			if (OperatingSystem.IsWindows())
			{
				await environment.Error.WriteLineAsync(
					"Starter helper scripts are POSIX sh scripts and are not generated on Windows. On Windows, credential profiles live in Windows Credential Manager "
					+ "unless a credential helper is configured; any .exe or .cmd program that speaks the linq2db credential helper protocol can be configured with '--credential-helper' or 'credentialHelper'.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			if (backend == null)
			{
				await environment.Error.WriteLineAsync("Option '--backend' must be specified for credentials helper init: secret-tool or pass.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			var resolver = new ConnectionSettingsResolver(environment);
			string path;

			if (output != null)
			{
				var resolved = resolver.ResolvePath(_output, output);

				if (resolved == null || string.Equals(resolved, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
					return StatusCodes.INVALID_ARGUMENTS;

				path = Path.GetFullPath(resolved);
			}
			else
			{
				var configHome = environment.GetEnvironmentVariable("XDG_CONFIG_HOME");

				if (string.IsNullOrEmpty(configHome) || !Path.IsPathRooted(configHome))
				{
					var home = environment.GetEnvironmentVariable("HOME");

					if (string.IsNullOrEmpty(home))
					{
						await environment.Error.WriteLineAsync("Cannot determine the default script location: neither XDG_CONFIG_HOME nor HOME is set. Use '--output'.");
						return StatusCodes.INVALID_ARGUMENTS;
					}

					configHome = Path.Combine(home, ".config");
				}

				path = Path.Combine(configHome, "linq2db", "helpers", backend + ".sh");
			}

			string? configFile = null;

			if (config != null)
			{
				configFile = resolver.ResolvePath(_config, config);

				if (configFile == null || string.Equals(configFile, ConnectionSettingsResolver.MissingEnvironmentVariable, StringComparison.Ordinal))
					return StatusCodes.INVALID_ARGUMENTS;
			}

			var template = CredentialHelperTemplates.Get(backend);

			if (template == null)
			{
				await environment.Error.WriteLineAsync($"Unknown credential helper backend '{backend}'. Expected secret-tool or pass.");
				return StatusCodes.INVALID_ARGUMENTS;
			}

			// Validate the configuration change before writing anything.
			JsonObject? root = null;

			if (configFile != null)
			{
				if (environment.FileExists(configFile))
				{
					if (!ConfigInitCommand.TryLoadRoot(environment, configFile, out root))
						return StatusCodes.EXPECTED_ERROR;
				}
				else
				{
					root = new JsonObject();
				}

				var defaultNode = root[QueryExecutionDefaults.DefaultProfileName];

				if (defaultNode is not (null or JsonObject))
				{
					await environment.Error.WriteLineAsync($"Configuration file '{configFile}' profile '{QueryExecutionDefaults.DefaultProfileName}' must be object.");
					return StatusCodes.EXPECTED_ERROR;
				}

				var existing = (defaultNode as JsonObject)?["credentialHelper"];

				if (existing != null && !force && !(existing is JsonValue value && value.TryGetValue<string>(out var existingPath) && string.Equals(existingPath, path, StringComparison.Ordinal)))
				{
					await environment.Error.WriteLineAsync($"Configuration file '{configFile}' profile '{QueryExecutionDefaults.DefaultProfileName}' already sets 'credentialHelper'. Use '--force' to replace it.");
					return StatusCodes.EXPECTED_ERROR;
				}
			}

			if (!CredentialHelperTemplates.TryWrite(path, template, force, out var writeError))
			{
				await environment.Error.WriteLineAsync(writeError);
				return StatusCodes.EXPECTED_ERROR;
			}

			await environment.Out.WriteLineAsync($"Created credential helper script '{path}' for backend '{backend}'. It is a starter script: review it, and edit it if your setup needs to.");

			if (root != null)
			{
				if (root[QueryExecutionDefaults.DefaultProfileName] is not JsonObject defaultProfile)
					root[QueryExecutionDefaults.DefaultProfileName] = defaultProfile = new JsonObject();

				defaultProfile["credentialHelper"] = path;

				var directory = Path.GetDirectoryName(configFile);
				if (!string.IsNullOrEmpty(directory))
					environment.CreateDirectory(directory);

				if (!await ConfigInitCommand.TryWriteConfiguration(environment, configFile!, root.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + Environment.NewLine))
					return StatusCodes.EXPECTED_ERROR;

				await environment.Out.WriteLineAsync($"Recorded it as 'credentialHelper' in profile '{QueryExecutionDefaults.DefaultProfileName}' of '{configFile}'.");
			}
			else
			{
				await environment.Out.WriteLineAsync($"Use it with '--credential-helper {path}', or set \"credentialHelper\": \"{path}\" in the '{QueryExecutionDefaults.DefaultProfileName}' profile of your configuration file.");
			}

			var backendCommand = CredentialHelperTemplates.GetBackendCommand(backend);

			if (!CredentialHelperCommandResolver.TryResolve(backendCommand, null, false, environment.GetEnvironmentVariable("PATH"), null, File.Exists, out _, out _))
				await environment.Error.WriteLineAsync($"Warning: '{backendCommand}' was not found on PATH. Install it ({CredentialHelperTemplates.GetBackendPackage(backend)}) before using the helper.");

			return StatusCodes.SUCCESS;
		}

		static bool ValidateProfile(ICliEnvironment environment, string? profile)
		{
			if (string.IsNullOrWhiteSpace(profile))
			{
				environment.Error.WriteLine("Option '--profile' must be specified.");
				return false;
			}

			if (profile.StartsWith("linq2db/", StringComparison.OrdinalIgnoreCase))
			{
				environment.Error.WriteLine("Option '--profile' must not include the automatic 'linq2db/' target prefix.");
				return false;
			}

			if (profile[0] == '/'
				|| profile[^1] == '/'
				|| profile.Any(char.IsControl))
			{
				environment.Error.WriteLine("Option '--profile' must be a non-empty target suffix without leading/trailing '/' or control characters.");
				return false;
			}

			return true;
		}
	}
